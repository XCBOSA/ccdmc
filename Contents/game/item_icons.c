static unsigned blend(unsigned a,unsigned b,unsigned tint) {
    unsigned color=0;
    for (int shift=0;shift<=16;shift+=8)
        color|=((((a>>shift)&255u)*(100-tint)+((b>>shift)&255u)*tint)/100u)<<shift;
    return color;
}
